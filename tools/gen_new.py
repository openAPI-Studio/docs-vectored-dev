#!/usr/bin/env python3
"""Write assets/new.js: when each doc page, and each section in it, went live.

docs.js reads this to put a "New" badge on recently published pages in the
sidebar and on recently added sections in the "On this page" rail. Nothing is
tagged by hand: the dates come from git history on the published branch.

  page date     the first commit on main that contains the file
  section date  the first commit on main whose copy of the file has an <h2>
                with that heading text, ignoring any "3." numbering (so a
                renumber is not news, but a reworded heading is)

History is walked with --first-parent, so a page written on a branch over a
week counts from the day its pull request was merged, not the day it was
started. Only the dates are stored; docs.js decides what is still "new"
(NEW_DAYS there), so badges expire by themselves without a rebuild.

Run from anywhere; .github/workflows/new-badges.yml runs it on every push to
main and commits the result:

    python3 tools/gen_new.py
"""
import glob, html, json, os, re, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'new.js')


def git(*args):
    return subprocess.run(['git', *args], cwd=ROOT, capture_output=True,
                          text=True, check=True).stdout


def slugify(s):
    # Mirrors slugify() in assets/docs.js: JS \w is ASCII-only.
    s = re.sub(r'[^\w]+', '-', s.lower(), flags=re.ASCII).strip('-')
    return s[:60]


H2 = re.compile(r'<h2\b([^>]*)>(.*?)</h2>', re.S | re.I)
ID = re.compile(r'\bid\s*=\s*["\']([^"\']+)["\']', re.I)


def section_ids(src):
    """[(id, key)] for the article's h2s, in page order.

    id is what docs.js ends up with, so the rail link can be matched. key is
    what history is matched on: the heading text without its "3." numbering,
    so inserting a section near the top, which renumbers everything below it,
    does not make every later section look new."""
    m = re.search(r'<article[^>]*class="[^"]*\bvc-doc\b[^"]*"[^>]*>(.*)</article>', src, re.S)
    body = m.group(1) if m else src
    used, ids = set(), []
    for attrs, inner in H2.findall(body):
        im = ID.search(attrs)
        text = ' '.join(html.unescape(re.sub(r'<[^>]+>', '', inner)).split())
        hid = im.group(1) if im else (slugify(text) or 'section')
        while hid in used:
            hid += '-1'
        used.add(hid)
        key = re.sub(r'^\d+(-\d+)*-', '', slugify(text)) or hid
        ids.append((hid, key))
    return ids


def doc_pages():
    """Every page that renders the docs shell (and so has a sidebar/rail)."""
    out = []
    for path in glob.glob(os.path.join(ROOT, '**', '*.html'), recursive=True):
        rel = os.path.relpath(path, ROOT).replace(os.sep, '/')
        if rel.startswith('.') or '/_' in rel or os.path.basename(rel) == 'print.html':
            continue
        with open(path, encoding='utf-8') as f:
            if 'assets/docs.js' in f.read():
                out.append(rel)
    return sorted(out)


def history(rel):
    """[(sha, date)] oldest first, on the first-parent line, for one file."""
    out = git('log', '--first-parent', '--reverse', '--format=%H %cs', '--', rel)
    return [tuple(line.split()) for line in out.splitlines() if line.strip()]


def main():
    pages, sections = {}, {}
    for rel in doc_pages():
        hist = history(rel)
        if not hist:
            continue  # not committed yet: it will be dated when it is
        pages[rel] = hist[0][1]
        seen = {}
        for sha, date in hist:
            try:
                src = git('show', '%s:%s' % (sha, rel))
            except subprocess.CalledProcessError:
                continue  # deleted in this commit
            for _, key in section_ids(src):
                seen.setdefault(key, date)
        # Only sections still on the page, and only those that arrived after
        # the page itself: on a brand-new page every section is new, and the
        # sidebar badge already says so.
        with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
            current = section_ids(f.read())
        later = {hid: seen[key] for hid, key in current
                 if key in seen and seen[key] > pages[rel]}
        if later:
            sections[rel] = later

    data = {'pages': pages, 'sections': sections}
    body = json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True)
    js = ('/* Generated by tools/gen_new.py — do not edit by hand.\n'
          '   When each doc page and section first went live on main (YYYY-MM-DD).\n'
          '   assets/docs.js turns recent ones into "New" badges. */\n'
          'window.VC_NEW = ' + body + ';\n')
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if old != js:
        with open(OUT, 'w', encoding='utf-8') as f:
            f.write(js)
    print('dated %d pages, %d with later sections' % (len(pages), len(sections)))


if __name__ == '__main__':
    main()
